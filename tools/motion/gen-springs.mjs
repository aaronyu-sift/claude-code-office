// Writes the spring tokens of public/app.css from public/js/motion.js, so the CSS and the script cannot drift apart.
//   node tools/motion/gen-springs.mjs          print the block
//   node tools/motion/gen-springs.mjs --write  replace the block between the markers in public/app.css
// test/motion.test.mjs fails when the block in app.css differs from what this prints.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { SPRING } from '../../public/js/motion.js';

export const START = '/* springs:start (generated by tools/motion/gen-springs.mjs from public/js/motion.js: edit the springs there and run it with --write) */';
export const END = '/* springs:end */';

export function block() {
  const lines = Object.entries(SPRING).map(([name, s]) => `  --spring-${name}: ${s.css}; --spring-${name}-ms: ${s.ms}ms;          /* duration ${s.duration} s, bounce ${s.bounce} */`);
  return `${START}\n${lines.join('\n')}\n  ${END}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = block();
  if (!process.argv.includes('--write')) console.log(text);
  else {
    const file = join(dirname(fileURLToPath(import.meta.url)), '../../public/app.css');
    const css = readFileSync(file, 'utf8'), a = css.indexOf('/* springs:start'), b = css.indexOf(END);
    if (a < 0 || b < 0) throw new Error('markers not found in app.css');
    writeFileSync(file, css.slice(0, a) + text + css.slice(b + END.length));
    console.log('app.css updated');
  }
}
