// Picks the templates of public/js/ofis-arrange-table.js: for every work part x soft part x door it tries N random templates (the same sampler the page falls back on), keeps the
// ones where every seat of the room has a way in from the door (or all but a few: a chair that stands in a corner is furniture, not a seat), scores them by how wide the aisles are
// and how few seats are shut in, and writes the three best that differ from each other.
//   node tools/arrange-pick.mjs [--n 300] [--only communal] [--out public/js/ofis-arrange-table.js] [--check]
// --check does not write: it exits 1 when a pair has no valid template or a template of the table no longer composes (what test/ofis-arrange.test.mjs also checks, much faster).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { WORK_IDS, SOFT_IDS, composeRoom, sampleTemplate } from '../public/js/ofis-arrange.js';
import { TABLE } from '../public/js/ofis-arrange-table.js';

const args = process.argv.slice(2);
const val = (f, d) => { const i = args.indexOf('--' + f); return i >= 0 ? args[i + 1] : d; };
const N = +val('n', 300), only = val('only'), check = args.includes('--check');
const OUT = val('out', join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'js', 'ofis-arrange-table.js'));
const DOORS = ['front', 'back'];

function rng(seed) { let a = seed | 0; return () => { a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const hashStr = s => { let h = 2166136261; for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return h >>> 0; };

// the narrowest the way to a seat gets (metres of clearance, capped), averaged over the seats in use
function aisle(room) {
  const r = room.router;
  let sum = 0, n = 0;
  for (const s of [room.chef, ...room.seats]) {
    let min = 0.7;
    const skip = new Set([s.piece]);
    for (let i = 0; i + 1 < s.approach.length; i++) {
      const [a, b] = [s.approach[i], s.approach[i + 1]], len = Math.hypot(b[0] - a[0], b[1] - a[1]), steps = Math.max(1, Math.ceil(len / 0.1));
      for (let k = 0; k <= steps; k++) min = Math.min(min, r.clearance(a[0] + (b[0] - a[0]) * k / steps, a[1] + (b[1] - a[1]) * k / steps, skip));
    }
    sum += min; n++;
  }
  return sum / n;
}

const out = {};
let bad = 0;
const t0 = Date.now();
for (const work of WORK_IDS) {
  if (only && only !== work) continue;
  for (const soft of SOFT_IDS) for (const door of DOORS) {
    const key = `${work}:${soft}:${door}`;
    if (check) {
      const list = TABLE[key] || [];
      const okAll = list.length >= 1 && list.every(tpl => composeRoom({ work, soft, tpl, door }).ok);
      if (!okAll) { bad++; console.log('BAD', key, list.length); }
      continue;
    }
    const rand = rng(hashStr(key)), found = [];
    for (let i = 0; i < N; i++) {
      const tpl = sampleTemplate(work, soft, rand);
      if (!tpl) continue;
      const room = composeRoom({ work, soft, tpl, door });
      if (!room.ok) continue;
      const a = aisle(room);
      found.push({ tpl, score: room.blocked.length * 0.25 - a * 2, blocked: room.blocked.length, aisle: a });
    }
    found.sort((p, q) => p.score - q.score);
    const keep = [];
    for (const f of found) {
      if (keep.every(k => k.tpl[0] !== f.tpl[0] || k.tpl[1] !== f.tpl[1] || Math.hypot(k.tpl[2] - f.tpl[2], k.tpl[3] - f.tpl[3]) > 1.2 || Math.hypot(k.tpl[4] - f.tpl[4], k.tpl[5] - f.tpl[5]) > 1.2)) keep.push(f);
      if (keep.length === 3) break;
    }
    if (!keep.length) { bad++; console.log('NONE', key, `(${found.length} valid)`); continue; }
    out[key] = keep.map(k => k.tpl);
    console.log(key.padEnd(24), `${found.length} valid of ${N};`, keep.map(k => `blocked ${k.blocked} aisle ${k.aisle.toFixed(2)}`).join(' | '));
  }
}
if (!check) {
  const lines = Object.entries(out).map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`);
  if (!only) writeFileSync(OUT, `// Templates for every pair of a work part and a soft part and each door: [rw, rs, wx, wz, sx, sz] (ofis-arrange.js lay). Generated by tools/arrange-pick.mjs: do not edit by hand.\nexport const TABLE = {\n${lines.join('\n')}\n};\n`);
  console.log(only ? '(--only: nothing written)' : 'wrote ' + OUT, `${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
process.exit(bad ? 1 : 0);
